test('event migration creates a single empty live event, code-free joining and separate practice',async()=>{
 const t=await eventDatabase(8);
 try{
  assert.equal((await t.snap(1)).live,null);
  const {id}=await t.cmd(0,'create',null,{title:'Trust No One',groups:1,size:6,traitors:1});
  assert.equal((await t.snap(1)).live.id,id);
  assert.equal((await t.snap(0,id)).players.length,0);
  await assert.rejects(()=>t.cmd(0,'create',null,{title:'Duplicate',groups:1,size:6,traitors:1}),/already exists/);
  await t.cmd(0,'joining',id,{open:true});await t.cmd(1,'join');await t.cmd(2,'join');
  assert.equal((await t.snap(1,id)).me.number,1);
  assert.equal((await t.snap(1,id)).me.name,'Player 01');
  assert.equal((await t.snap(0,id)).players.length,2);
  const roster=(await t.snap(0,id)).players;
  const boardToken=(await t.snap(0,id)).display_token;
  assert.ok((await t.board(boardToken)).players.every(p=>p.account_name===undefined));
  await t.cmd(0,'callsign',id,{group:roster[0].group,player:roster[0].id,name:'Approved Raven',reason:'NCO approved this callsign'});
  assert.equal((await t.board(boardToken)).players.find(p=>p.id===roster[0].id).name,'Approved Raven');
  await t.cmd(0,'withdraw',id,{group:roster[1].group,player:roster[1].id,reason:'Left before briefing'});
  assert.equal((await t.board(boardToken)).players.find(p=>p.id===roster[1].id).role,null);
  const rehearsal=await t.cmd(0,'create',null,{title:'NCO rehearsal',practice:true,groups:1,size:6,traitors:1});
  assert.equal((await t.snap(0,rehearsal.id)).practice,true);
  assert.equal((await t.snap(1)).live.id,id);
  await assert.rejects(()=>t.snap(1,rehearsal.id),/not a member/);
 }finally{await t.close();}
});

test('runoffs use fresh ballot IDs; recovery preserves roles; redundant murders and final wins are consistent',async()=>{
 const t=await eventDatabase(9);
 try{
  const {id}=await t.cmd(0,'create',null,{title:'Full round rehearsal',practice:true,groups:1,size:7,traitors:2});
  await t.cmd(0,'joining',id,{open:true});for(let i=1;i<=6;i++)await t.cmd(i,'join',id,{practice_event:id});
  await t.cmd(0,'prepare_roles',id);await t.cmd(0,'release_roles',id);let state=await t.snap(0,id);
  const g=state.groups[0].id;const index=p=>Number(p.account_name.split(' ')[1]);let active=state.players;
  let faithful=state.players.filter(p=>p.role==='Faithful');const traitors=state.players.filter(p=>p.role==='Traitor');
  await t.cmd(0,'assign_staff',id,{name:'Person 7',groups:[g]});
  await t.cmd(0,'mission',id,{mission:0});await t.cmd(0,'discussion',id,{group:g});await t.cmd(0,'open_vote',id,{group:g});
  const first=(await t.snap(0,id)).groups[0].ballot.id;
  const a=faithful[0].id,b=faithful[1].id;let other=0;
  for(const p of active){let target=p.id===a?b:p.id===b?a:other++%2?a:b;await t.cmd(index(p),'vote',id,{ballot:first,target});}
  await t.cmd(0,'close_vote',id,{group:g});assert.equal((await t.snap(0,id)).groups[0].ballot.status,'tie');
  await t.cmd(0,'runoff',id,{group:g});const runoff=(await t.snap(0,id)).groups[0].ballot.id;assert.notEqual(runoff,first);
  await assert.rejects(()=>t.cmd(index(active[0]),'vote',id,{ballot:first,target:a}),/ballot has changed/);
  await assert.rejects(()=>t.cmd(0,'close_vote',id,{group:g,expected_ballots:{[g]:first}}),/ballot has changed/);
  const notCandidate=active.find(p=>p.id!==a&&p.id!==b);await assert.rejects(()=>t.cmd(index(notCandidate),'vote',id,{ballot:runoff,target:faithful[2].id}),/eligible active player/);
  other=0;for(const p of active){const target=p.id===a?b:p.id===b?a:other++%2?a:b;await t.cmd(index(p),'vote',id,{ballot:runoff,target});}
  await t.cmd(0,'close_vote',id,{group:g});await assert.rejects(()=>t.cmd(0,'runoff',id,{group:g}),/one runoff/);
  await assert.rejects(()=>t.cmd(7,'random_draw',id,{group:g}),/not permitted|main host/);
  await t.cmd(0,'random_draw',id,{group:g});state=await t.snap(0,id);const firstReveal=state.reveals[0];
  assert.ok([a,b].includes(firstReveal.target));await t.cmd(0,'publish',id,{group:g,reveal:firstReveal.id});
  state=await t.snap(0,id);active=state.players.filter(p=>p.status==='Active');faithful=active.filter(p=>p.role==='Faithful');
  const beforeRecovery=await t.snap(index(faithful[0]),id);const oldRole=beforeRecovery.me.role;
  await t.rpc(7,'tno_recover',{eid:id,pid:faithful[0].id,new_pin:'0456'});
  await assert.rejects(()=>t.snap(index(faithful[0]),id),/Sign in first/);
  await assert.rejects(()=>t.rpc(index(faithful[0]),'tno_login',{display_name:faithful[0].account_name,pin:'0123',register:false}),/not recognised/);
  await t.rpc(index(faithful[0]),'tno_login',{display_name:faithful[0].account_name,pin:'0456',register:false});
  assert.equal((await t.snap(index(faithful[0]),id)).me.role,oldRole);
  const audit=JSON.stringify((await t.snap(0,id)).audit);assert.ok(!audit.includes('0456'));
  await t.cmd(0,'open_murder',id,{group:g,slot:0,decider:traitors[0].id});const wid=(await t.snap(0,id)).windows[0].id;
  await assert.rejects(()=>t.cmd(0,'open_murder',id,{group:g,slot:1}),/current murder opportunity/);
  await t.cmd(index(traitors[0]),'propose',id,{opportunity:wid,target:faithful[0].id});
  await t.cmd(index(traitors[1]),'propose',id,{opportunity:wid,target:faithful[1].id});
  await t.cmd(0,'lock_murder',id,{group:g});state=await t.snap(0,id);const murder=state.reveals.find(r=>r.opportunity===wid);
  assert.equal(murder.target,faithful[0].id);
  await t.cmd(0,'discussion',id,{group:g});await t.cmd(0,'open_vote',id,{group:g});
  const second=(await t.snap(0,id)).groups[0].ballot.id;
  await t.cmd(0,'close_vote',id,{group:g});assert.equal((await t.snap(0,id)).groups[0].ballot.status,'empty');
  await assert.rejects(()=>t.cmd(0,'random_draw',id,{group:g}),/tied runoff/);
  await t.cmd(0,'reopen_ballot',id,{group:g});
  for(const p of active)await t.cmd(index(p),'vote',id,{ballot:second,target:p.id===faithful[0].id?traitors[0].id:faithful[0].id});
  await t.cmd(0,'close_vote',id,{group:g});state=await t.snap(0,id);const secondReveal=state.reveals.find(r=>r.ballot===second);
  await t.cmd(0,'publish',id,{group:g,reveal:secondReveal.id});
  const token=(await t.snap(0,id)).display_token;assert.equal((await t.board(token)).players.find(p=>p.id===faithful[0].id).status,'Banished');
  await t.cmd(0,'publish',id,{group:g,reveal:murder.id});state=await t.snap(0,id);
  assert.equal(state.reveals.find(r=>r.id===murder.id).redundant,true);
  assert.equal(state.groups[0].done,false); // no Mafia-style parity win
  assert.equal(state.players.filter(p=>p.status==='Murdered').length,0);
  await t.cmd(0,'mission',id,{group:g,mission:1});await t.cmd(0,'open_murder',id,{group:g,slot:1});
  const plain=(await t.snap(0,id)).windows.find(w=>w.slot===1);await t.cmd(0,'discussion',id,{group:g});
  state=await t.snap(0,id);assert.equal(state.windows.find(w=>w.id===plain.id).success,false);
  const noMurder=state.reveals.find(r=>r.opportunity===plain.id);await t.cmd(0,'publish',id,{group:g,reveal:noMurder.id});
  await t.cmd(0,'open_vote',id,{group:g});state=await t.snap(0,id);const third=state.groups[0].ballot.id;
  active=state.players.filter(p=>p.status==='Active');const finalTarget=active.find(p=>p.role==='Faithful');
  for(const p of active)await t.cmd(index(p),'vote',id,{ballot:third,target:p.id===finalTarget.id?traitors[0].id:finalTarget.id});
  await t.cmd(0,'close_vote',id,{group:g});const thirdReveal=(await t.snap(0,id)).reveals.find(r=>r.ballot===third);
  await t.cmd(0,'publish',id,{group:g,reveal:thirdReveal.id});await t.cmd(0,'finale',id,{group:g});
  await t.cmd(0,'finish',id);state=await t.snap(0,id);assert.equal(state.groups[0].winner,'Traitors');
  const exported=await t.rpc(0,'tno_export',{eid:id});assert.equal(exported.players.length,6);assert.ok(!JSON.stringify(exported).includes('pin_hash'));
  await assert.rejects(()=>t.rpc(7,'tno_export',{eid:id}),/main host/);
  await t.cmd(0,'delete',id,{confirm:state.title});await assert.rejects(()=>t.snap(0,id),/not found/);
 }finally{await t.close();}
});

test('50-player load, group-scoped NCO access, timer control, private votes, shields and early victories',async(tcase)=>{
 const t=await eventDatabase(55);const started=performance.now();
 try{
  const {id}=await t.cmd(0,'create',null,{title:'Full event',groups:5,size:10,traitors:2});
  await t.cmd(0,'configure',id,{title:'Full event',date:'2026-10-31',shields:true,chat:false,groups:['Raven','Ember','Thorn','Ash','Vesper'].map(name=>({name,size:10,traitors:2}))});
  await t.cmd(0,'joining',id,{open:true});
  await Promise.all(Array.from({length:50},(_,i)=>t.cmd(i+1,'join')));
  let state=await t.snap(0,id);assert.equal(state.players.length,50);
  const groups=state.groups;const g=groups[0].id;const h=groups[1].id;
  await t.cmd(0,'assign_staff',id,{name:'Person 51',groups:[g]});
  assert.equal((await t.snap(51,id)).groups.length,1);
  await assert.rejects(()=>t.cmd(51,'score',id,{group:h,mission:0,points:5,reason:'Not allowed'}),/not permitted/);
  await assert.rejects(()=>t.cmd(1,'assign_staff',id,{name:'Person 1',groups:[g]}),/Only the host/);
  await t.cmd(0,'prepare_roles',id);state=await t.snap(0,id);
  assert.ok(state.players.every(p=>p.role));
  assert.equal((await t.snap(1,id)).me.role,null);
  await assert.rejects(()=>t.cmd(52,'join'),/closed/);
  await t.cmd(0,'release_roles',id);
  await assert.rejects(()=>t.cmd(0,'prepare_roles',id),/already prepared/);
  const groupPlayers=state.players.filter(p=>p.group===g);const traitors=groupPlayers.filter(p=>p.role==='Traitor');const faithful=groupPlayers.filter(p=>p.role==='Faithful');
  const index=p=>Number(p.account_name.split(' ')[1]);
  const faithfulState=await t.snap(index(faithful[0]),id);
  assert.ok(faithfulState.players.filter(p=>p.id!==faithful[0].id).every(p=>p.role===null));
  assert.equal(faithfulState.windows.length,0);
  const outsider=state.players.find(p=>p.group===h&&p.role==='Traitor');
  assert.ok((await t.snap(index(traitors[0]),id)).players.filter(p=>p.group!==g).every(p=>p.role===null));
  const nco=await t.snap(51,id);assert.ok(nco.players.every(p=>p.group===g));
  await t.cmd(0,'mission',id,{mission:0});
  await t.cmd(0,'pause',id,{group:g});let paused=(await t.snap(index(faithful[0]),id)).groups.find(x=>x.id===g);
  assert.equal(paused.paused,true);assert.equal(paused.deadline,null);
  await t.cmd(0,'extend',id,{group:g,seconds:60});await t.cmd(0,'resume',id,{group:g});
  assert.ok((await t.snap(51,id)).groups[0].deadline);
  await t.cmd(51,'score',id,{group:g,mission:0,points:50,reason:'First stage completed'});
  await assert.rejects(()=>t.cmd(51,'score',id,{group:g,mission:0,points:101,reason:'Too high'}),/valid mission points/);
  await t.cmd(index(faithful[0]),'help',id);await t.cmd(index(faithful[0]),'help',id);
  assert.equal((await t.snap(51,id)).helps.length,1);
  await t.cmd(0,'discussion',id,{group:g});await t.cmd(0,'open_vote',id,{group:g});
  const otherGroupBefore=(await t.snap(index(outsider),id)).groups.find(x=>x.id===h);assert.equal(otherGroupBefore.phase,'Mission');
  await assert.rejects(async()=>t.cmd(index(faithful[0]),'vote',id,{target:outsider.id,ballot:(await t.snap(0,id)).groups.find(x=>x.id===g).ballot.id}),/eligible active player/);
  const firstBallot=(await t.snap(0,id)).groups.find(x=>x.id===g).ballot.id;
  await Promise.all(groupPlayers.map(p=>t.cmd(index(p),'vote',id,{ballot:firstBallot,target:p.id===traitors[0].id?faithful[0].id:traitors[0].id})));
  const ballotView=(await t.snap(index(faithful[0]),id)).groups.find(x=>x.id===g).ballot;
  assert.equal(ballotView.tally,undefined);
  await t.cmd(0,'close_vote',id,{group:g});state=await t.snap(0,id);
  const banishment=state.reveals.find(r=>r.group_id===g&&r.kind==='Banished');
  assert.equal(banishment.target,traitors[0].id);
  const token=state.display_token;
  assert.equal((await t.board(token)).reveals.length,0);
  await t.cmd(0,'publish',id,{group:g,reveal:banishment.id});
  await assert.rejects(()=>t.cmd(0,'publish',id,{group:g,reveal:banishment.id}),/already public/);
  await t.cmd(0,'reveal_role',id,{group:g,reveal:banishment.id});
  await assert.rejects(()=>t.cmd(index(traitors[0]),'vote',id,{target:faithful[0].id,ballot:firstBallot}),/closed|eligible/);
  await t.cmd(0,'open_murder',id,{group:g,slot:0});
  await t.cmd(0,'shield',id,{group:g,player:faithful[0].id,slot:0});
  await t.cmd(index(traitors[1]),'propose',id,{target:faithful[0].id,opportunity:(await t.snap(0,id)).windows.find(w=>w.group_id===g&&w.slot===0).id});
  await assert.rejects(()=>t.cmd(index(traitors[1]),'message',id,{text:'<script>bad</script>'}),/Free text/);
  await t.cmd(index(traitors[1]),'message',id,{text:'I agree.'});
  assert.equal((await t.snap(index(traitors[0]),id)).messages.length,0);
  assert.equal((await t.snap(index(faithful[0]),id)).messages.length,0);
  await t.cmd(0,'lock_murder',id,{group:g});state=await t.snap(0,id);
  const blocked=state.reveals.find(r=>r.group_id===g&&r.kind==='Murdered');assert.equal(blocked.target,null);
  await t.cmd(0,'publish',id,{group:g,reveal:blocked.id});
  await assert.rejects(()=>t.cmd(0,'open_murder',id,{group:g,slot:0}),/opportunity/);
  await t.cmd(0,'mission',id,{group:g,mission:1});await t.cmd(0,'open_murder',id,{group:g,slot:1});
  await t.cmd(0,'objective',id,{group:g,target:faithful[1].id,text:'Get the target to say the agreed phrase.'});
  await t.cmd(index(traitors[1]),'report_objective',id,{opportunity:(await t.snap(0,id)).windows.find(w=>w.group_id===g&&w.slot===1).id});
  assert.equal((await t.board(token)).players.find(p=>p.id===faithful[1].id).status,'Active');
  await t.cmd(51,'confirm_objective',id,{group:g,opportunity:(await t.snap(0,id)).windows.find(w=>w.group_id===g&&w.slot===1).id,success:true,reason:'NCO witnessed the phrase'});
  state=await t.snap(0,id);const pending=state.reveals.find(r=>r.group_id===g&&r.opportunity&&!r.published&&r.target);
  assert.equal(pending.target,faithful[1].id);
  const publicPending=await t.board(token);assert.equal(publicPending.players.find(p=>p.id===faithful[1].id).status,'Active');
  assert.equal(JSON.stringify(publicPending).includes('agreed phrase'),false);
  await t.cmd(0,'discussion',id,{group:g});await t.cmd(0,'open_vote',id,{group:g});
  const secondBallot=(await t.snap(0,id)).groups.find(x=>x.id===g).ballot.id;
  for(const p of groupPlayers.filter(p=>p.id!==traitors[0].id))await t.cmd(index(p),'vote',id,{ballot:secondBallot,target:p.id===traitors[1].id?faithful[0].id:traitors[1].id});
  await t.cmd(0,'close_vote',id,{group:g});state=await t.snap(0,id);
  const secondBan=state.reveals.find(r=>r.group_id===g&&r.kind==='Banished'&&!r.published);
  await t.cmd(0,'publish',id,{group:g,reveal:secondBan.id});
  assert.equal((await t.snap(0,id)).groups.find(x=>x.id===g).done,false);
  await t.cmd(0,'publish',id,{group:g,reveal:pending.id});
  state=await t.snap(0,id);assert.equal(state.groups.find(x=>x.id===g).done,true);
  assert.equal(state.players.find(p=>p.id===faithful[1].id).status,'Murdered');
  assert.equal(state.groups.find(x=>x.id===g).winner,null); // winners remain staged until final release
  await assert.rejects(()=>t.cmd(index(traitors[1]),'message',id,{text:'I agree.'}),/active Traitor/);
  const roundsStart=performance.now();
  const snapshots=await Promise.all([...Array.from({length:50},(_,i)=>t.snap(i+1,id)),t.snap(0,id),t.snap(51,id),t.board(token)]);
  assert.equal(snapshots.length,53);assert.ok(snapshots.every(s=>s.id===id));
  const projector=snapshots[52];assert.equal(projector.windows,undefined);assert.equal(projector.messages,undefined);
  const loadMs=Math.round(performance.now()-roundsStart);const totalMs=Math.round(performance.now()-started);
  tcase.diagnostic(`50 players + host/NCO/projector: 53 concurrently submitted snapshot requests completed in ${loadMs}ms; scenario ${totalMs}ms. Embedded Postgres serialises queries; not a network/radio concurrency benchmark.`);
 }finally{await t.close();}
});
